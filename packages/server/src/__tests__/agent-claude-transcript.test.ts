import { afterAll, beforeAll, describe, expect, test } from "bun:test";
import { mkdir, mkdtemp, rm, utimes, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import {
  claudeSessionsDir,
  listClaudeSessions,
  readClaudeTranscript,
} from "../agent/claude/transcript.ts";

const CWD = "/work/my-app";
let home: string;
const before = process.env.CLAUDE_CONFIG_DIR;

const line = (o: Record<string, unknown>) => JSON.stringify(o);
const user = (content: unknown, extra: Record<string, unknown> = {}) =>
  line({
    type: "user",
    timestamp: "2026-10-01T10:00:00.000Z",
    message: { role: "user", content },
    ...extra,
  });
const assistant = (content: unknown[]) =>
  line({
    type: "assistant",
    timestamp: "2026-10-01T10:00:05.000Z",
    message: { role: "assistant", content },
  });

async function session(id: string, lines: string[], at: Date) {
  const path = join(claudeSessionsDir(CWD), `${id}.jsonl`);
  await writeFile(path, `${lines.join("\n")}\n`);
  await utimes(path, at, at);
}

beforeAll(async () => {
  home = await mkdtemp(join(tmpdir(), "velloo-claude-home-"));
  process.env.CLAUDE_CONFIG_DIR = home;
  await mkdir(claudeSessionsDir(CWD), { recursive: true });
  await session(
    "older",
    [
      user("<command-name>/clear</command-name>"),
      user("Make the **pricing** page denser"),
      assistant([{ type: "text", text: "On it." }]),
    ],
    new Date("2026-10-01T10:00:00Z"),
  );
  await session(
    "newer",
    [
      user("Caveat: the messages below were generated by the user", { isMeta: true }),
      user("Fix the header\nand the footer"),
      assistant([
        { type: "text", text: "Reading it first." },
        { type: "tool_use", id: "tu1", name: "Bash", input: { command: "ls" } },
        { type: "tool_use", id: "tu2", name: "Read", input: { file_path: "a.ts" } },
      ]),
      user([{ type: "tool_result", tool_use_id: "tu1", content: "a.ts" }], {
        toolUseResult: { stdout: "a.ts", stderr: "" },
      }),
      line({ type: "custom-title", customTitle: "Header fixes" }),
      user("Now the footer"),
      assistant([{ type: "text", text: "Done." }]),
    ],
    new Date("2026-10-02T10:00:00Z"),
  );
  await session("empty", [user("<local-command-stdout>ok</local-command-stdout>")], new Date());
});

afterAll(async () => {
  if (before === undefined) delete process.env.CLAUDE_CONFIG_DIR;
  else process.env.CLAUDE_CONFIG_DIR = before;
  await rm(home, { recursive: true, force: true });
});

describe("Claude Code sessions kept for a directory", () => {
  test("are listed newest first, named by their title or first prompt", async () => {
    const listed = await listClaudeSessions(CWD);
    expect(listed.map((e) => [e.providerSessionId, e.title])).toEqual([
      ["newer", "Header fixes"],
      ["older", "Make the **pricing** page denser"],
    ]);
  });

  test("another directory has none", async () => {
    expect(await listClaudeSessions("/work/other-app")).toEqual([]);
  });

  test("replay as turns: one per prompt, tools settled by their results", async () => {
    const turns = await readClaudeTranscript(CWD, "newer");
    expect(turns).toHaveLength(2);
    const [first, second] = turns;
    expect(first?.items.map((i) => i.kind)).toEqual(["user", "agent-text", "command", "tool"]);
    expect(first?.items[0]).toMatchObject({ kind: "user", text: "Fix the header\nand the footer" });
    expect(first?.items[2]).toMatchObject({ kind: "command", status: "completed", output: "a.ts" });
    // The Read never got a result: that session ended mid-turn.
    expect(first?.items[3]).toMatchObject({ kind: "tool", status: "failed" });
    expect(first?.status).toBe("interrupted");
    expect(second?.items.map((i) => i.kind)).toEqual(["user", "agent-text"]);
    expect(second?.status).toBe("completed");
  });

  test("a session that isn't there replays nothing", async () => {
    expect(await readClaudeTranscript(CWD, "missing")).toEqual([]);
  });
});
